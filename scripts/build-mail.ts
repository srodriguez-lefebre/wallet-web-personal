import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath, pathToFileURL } from "node:url";

import { build } from "esbuild";

const root = fileURLToPath(new URL("..", import.meta.url));
const output = new URL("../mail-service/normalization.gs", import.meta.url);

export async function createMailBundle() {
  const result = await build({
    absWorkingDir: root,
    entryPoints: ["mail-service/runtime.ts"],
    bundle: true,
    write: false,
    format: "iife",
    globalName: "WalletMail",
    platform: "neutral",
    target: "es2019",
    charset: "utf8",
    legalComments: "none",
    banner: {
      js: "// Generated by npm run mail:build. Edit the TypeScript sources, not this file.",
    },
  });
  const compiled = result.outputFiles[0]?.text;
  if (!compiled) throw new Error("Mail build produced no output");
  return compiled;
}

async function main() {
  const compiled = await createMailBundle();
  if (process.argv.includes("--check")) {
    if ((await readFile(output, "utf8")) !== compiled)
      throw new Error("Generated mail runtime is stale. Run npm run mail:build.");
  } else await writeFile(output, compiled, "utf8");
}

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) await main();
